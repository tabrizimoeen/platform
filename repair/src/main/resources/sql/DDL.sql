create table repairs.repair_shop
(
    id         bigserial
        primary key,
    name       varchar(255) not null,
    owner_name varchar(255),
    phone      varchar(255),
    created_at timestamp default now()
);

alter table repairs.repair_shop
    owner to postgres;

create table repairs.users
(
    id         bigserial
        primary key,
    username   varchar(255) not null,
    password   varchar(255) not null,
    role       varchar(255) default 'STAFF'::character varying,
    shop_id    bigint       not null
        references repairs.repair_shop,
    created_at timestamp    default now(),
    active     boolean,
    full_name  varchar(255)
);

alter table repairs.users
    owner to postgres;

create table repairs.customers
(
    id         bigserial
        primary key,
    name       varchar(255) not null,
    phone      varchar(255) not null,
    shop_id    bigint       not null
        references repairs.repair_shop,
    created_at timestamp default now(),
    updated_at timestamp default now()
);

alter table repairs.customers
    owner to postgres;

create index idx_customers_phone
    on repairs.customers (phone);

create unique index uk_customer_phone_shop
    on repairs.customers (phone, shop_id);

create table repairs.repair_orders
(
    id                  bigserial
        primary key,
    customer_id         bigint                                             not null
        references repairs.customers
            on delete cascade,
    shop_id             bigint                                             not null
        references repairs.repair_shop
            on delete cascade,
    device_model        varchar(255)                                       not null,
    imei                varchar(50),
    problem_description text,
    status              varchar(255) default 'RECEIVED'::character varying not null,
    estimated_cost      numeric(38, 2),
    final_cost          numeric(38, 2),
    created_at          timestamp    default now(),
    updated_at          timestamp    default now()
);

alter table repairs.repair_orders
    owner to postgres;

create index idx_repair_customer
    on repairs.repair_orders (customer_id);

create index idx_repair_imei
    on repairs.repair_orders (imei);

create index idx_repair_status
    on repairs.repair_orders (status);

create table repairs.repair_logs
(
    id         bigserial
        primary key,
    repair_id  bigint       not null
        references repairs.repair_orders
            on delete cascade,
    shop_id    bigint       not null
        references repairs.repair_shop,
    message    varchar(255) not null,
    status     varchar(50),
    created_at timestamp default now()
);

alter table repairs.repair_logs
    owner to postgres;

create table repairs.invoices
(
    id              bigserial
        primary key,
    repair_order_id bigint,
    amount          numeric(10, 2),
    paid            boolean   default false,
    shop_id         bigint not null
        references repairs.repair_shop,
    created_at      timestamp default now()
);

alter table repairs.invoices
    owner to postgres;

